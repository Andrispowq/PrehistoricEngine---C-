-- Repository-local CMake exporter. Premake remains the source of target/file lists.
-- Generate on the intended host; baked platform filters are host-specific.
newaction {
    trigger = "cmake",
    description = "Generate host-specific CMake targets for CLion",
    valid_kinds = { "StaticLib", "ConsoleApp" },
    valid_languages = { "C", "C++" },
    onWorkspace = function(wks)
        local root = wks.location
        local out = assert(io.open(path.join(root, "CMakeLists.txt"), "w"))
        local function emit(s) out:write(s .. "\n") end
        local function quote(s)
            return '"' .. s:gsub('\\', '/'):gsub('"', '\\"') .. '"'
        end
        local function relative(s) return quote(path.getrelative(root, s)) end
        emit('# Generated by premake5 cmake; edit premake5.lua or scripts/premake-cmake.lua.')
        emit('cmake_minimum_required(VERSION 3.21)')
        emit('project(PrehistoricEngine LANGUAGES C CXX)')
        emit('set(CMAKE_CXX_STANDARD 17)')
        emit('set(CMAKE_CXX_STANDARD_REQUIRED ON)')
        emit('set(CMAKE_EXPORT_COMPILE_COMMANDS ON)')
        emit('set(CMAKE_CONFIGURATION_TYPES "Debug;Release;Distribution" CACHE STRING "" FORCE)')
        emit('if(NOT CMAKE_BUILD_TYPE)\n  set(CMAKE_BUILD_TYPE Debug CACHE STRING "" FORCE)\nendif()')
        emit('set(CMAKE_RUNTIME_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/bin")')
        emit('set(CMAKE_ARCHIVE_OUTPUT_DIRECTORY "${CMAKE_BINARY_DIR}/lib")')
        if os.host() == "macosx" then
            emit('enable_language(OBJC OBJCXX)')
            emit('set(CMAKE_OBJCXX_STANDARD 17)')
            emit('set(CMAKE_OBJCXX_STANDARD_REQUIRED ON)')
            -- Resolve the loader at configure time, including SDK-only installations.
            emit('find_library(PREHISTORIC_VULKAN_LIBRARY NAMES vulkan HINTS "$ENV{VULKAN_SDK}/lib" REQUIRED)')
            emit('find_path(PREHISTORIC_VULKAN_INCLUDE_DIR vulkan/vulkan.h HINTS "$ENV{VULKAN_SDK}/include" REQUIRED)')
            emit('get_filename_component(PREHISTORIC_VULKAN_LIBRARY_DIR "${PREHISTORIC_VULKAN_LIBRARY}" DIRECTORY)')
            emit('list(APPEND CMAKE_BUILD_RPATH "${PREHISTORIC_VULKAN_LIBRARY_DIR}")')
        end

        local function nativeOpenAL(prj)
            return os.host() == "macosx" and prj.name == "OpenAL"
        end
        if os.host() == "macosx" then
            emit('include(scripts/native-openal.cmake)')
        end

        for prj in premake.workspace.eachproject(wks) do
            if not nativeOpenAL(prj) then
                local cfg = premake.project.getconfig(prj, "Debug")
                emit((cfg.kind == "StaticLib" and 'add_library(' .. prj.name .. ' STATIC' or 'add_executable(' .. prj.name))
                for _, file in ipairs(cfg.files) do
                    if os.isfile(file) then emit('  ' .. relative(file))
                    elseif path.getextension(file) == '.h' then
                        print('Skipping absent IDE header: ' .. path.getrelative(root, file))
                    else error('Missing source: ' .. file) end
                end
                emit(')')
                for _, file in ipairs(cfg.files) do
                    if path.getextension(file) == '.mm' then
                        emit('set_source_files_properties(' .. relative(file) .. ' PROPERTIES SKIP_PRECOMPILE_HEADERS ON)')
                    end
                end
            end
        end
        for prj in premake.workspace.eachproject(wks) do
            if not nativeOpenAL(prj) then
                for cfg in premake.project.eachconfig(prj) do
                    local condition = '$<CONFIG:' .. cfg.buildcfg .. '>'
                    local function values(command, list, paths)
                        if #list == 0 then return end
                        emit(command .. '(' .. prj.name .. ' PRIVATE')
                        for _, value in ipairs(list) do
                            -- Consumers inherit the matching upstream AL headers from OpenAL.
                            if not (paths and os.host() == "macosx" and
                                value:find("vendor/OpenAL%-Soft/include")) then
                                if paths and os.host() == "macosx" and value:find("Dependencies/include/Vulkan") then
                                    value = '${PREHISTORIC_VULKAN_INCLUDE_DIR}'
                                elseif paths then
                                    value = '${CMAKE_CURRENT_SOURCE_DIR}/' .. path.getrelative(root, value)
                                end
                                emit('  ' .. quote('$<' .. condition .. ':' .. value .. '>'))
                            end
                        end
                        emit(')')
                    end
                    values('target_include_directories', cfg.includedirs, true)
                    values('target_link_directories', cfg.libdirs, true)
                    for _, value in ipairs(cfg.undefines) do
                        values('target_compile_options', { '-U' .. value }, false)
                    end
                    values('target_compile_definitions', cfg.defines, false)
                end
                local cfg = premake.project.getconfig(prj, "Debug")
                emit('target_compile_options(' .. prj.name .. ' PRIVATE')
                emit('  "$<$<AND:$<CONFIG:Debug>,$<NOT:$<CXX_COMPILER_ID:MSVC>>>:-g>"')
                emit('  "$<$<AND:$<NOT:$<CONFIG:Debug>>,$<NOT:$<CXX_COMPILER_ID:MSVC>>>:-O2>"')
                emit(')')
                if cfg.pchheader then
                    emit('target_precompile_headers(' .. prj.name .. ' PRIVATE ' .. quote('<' .. cfg.pchheader .. '>') .. ')')
                end
                -- PUBLIC propagates static-library dependencies to the applications.
                if #cfg.links > 0 then
                    emit('target_link_libraries(' .. prj.name .. ' PUBLIC')
                    for _, link in ipairs(cfg.links) do
                        if os.host() == "macosx" and link == "vulkan" then emit('  "${PREHISTORIC_VULKAN_LIBRARY}"')
                        elseif path.isabsolute(link) then emit('  ' .. quote('${CMAKE_CURRENT_SOURCE_DIR}/' .. path.getrelative(root, link)))
                        else emit('  ' .. quote(link)) end
                    end
                    emit(')')
                end
                if prj.name == "Prehistoric" or prj.name == "PrehistoricEditor" then
                    emit('set_property(TARGET ' .. prj.name .. ' PROPERTY VS_DEBUGGER_WORKING_DIRECTORY "${CMAKE_CURRENT_SOURCE_DIR}/' .. prj.name .. '")')
                end
            end
        end
        emit('include(scripts/vulkan-compute-smoke.cmake)')
        emit('message(STATUS "Generated build graph; see MACOS_PORT.md for platform support")')
        out:close()
    end
}
